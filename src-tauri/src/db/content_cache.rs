use rusqlite::{params, Connection, Result};
use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CachedContent {
    pub id: Option<i64>,
    pub concept_id: String,
    pub content_type: String,
    pub payload_json: String,
    pub model_version: Option<String>,
    pub created_at: String,
    /// HMAC-SHA256 hex digest for integrity verification.
    #[serde(default)]
    pub content_hash: Option<String>,
}

/// Classify a mastery score into a coarse band so cache lookups return
/// content appropriate for the learner's current level.
/// Bands: "low" (< 0.3), "mid" (0.3–0.6), "high" (> 0.6).
pub fn mastery_band(score: f64) -> &'static str {
    if score < 0.3 {
        "low"
    } else if score <= 0.6 {
        "mid"
    } else {
        "high"
    }
}

/// Insert a new cache entry with an HMAC integrity hash.
/// Returns the new row id.
/// Also prunes old entries for the same concept+type to prevent bloat (keeps most recent 3).
pub fn insert_cache_entry(conn: &Connection, entry: &CachedContent) -> Result<i64> {
    insert_cache_entry_with_mastery(conn, entry, None)
}

/// Insert a cache entry tagged with the learner's current mastery band.
pub fn insert_cache_entry_with_mastery(
    conn: &Connection,
    entry: &CachedContent,
    mastery_score: Option<f64>,
) -> Result<i64> {
    // Embed mastery band tag in payload so cache lookups can verify freshness
    let payload = if let Some(score) = mastery_score {
        let band = mastery_band(score);
        format!("{}<!-- mastery_band:{} -->", entry.payload_json, band)
    } else {
        entry.payload_json.clone()
    };

    // Compute HMAC for the payload (including band tag)
    let hmac_hex = match crate::cache_integrity::get_or_create_secret(conn) {
        Ok(secret) => Some(crate::cache_integrity::compute_hmac(
            &secret,
            &entry.concept_id,
            &entry.content_type,
            &payload,
        )),
        Err(_) => None,
    };

    conn.execute(
        "INSERT INTO content_cache
         (concept_id, content_type, payload_json, model_version, created_at, content_hash)
         VALUES (?1, ?2, ?3, ?4, ?5, ?6)",
        params![
            entry.concept_id,
            entry.content_type,
            payload,
            entry.model_version,
            entry.created_at,
            hmac_hex,
        ],
    )?;
    let id = conn.last_insert_rowid();

    // Keep only the 3 most recent entries per concept+type
    conn.execute(
        "DELETE FROM content_cache
         WHERE concept_id = ?1 AND content_type = ?2
           AND id NOT IN (
               SELECT id FROM content_cache
               WHERE concept_id = ?1 AND content_type = ?2
               ORDER BY created_at DESC LIMIT 3
           )",
        params![entry.concept_id, entry.content_type],
    )?;

    Ok(id)
}

/// Look up a cached entry by concept_id and content_type.
/// Returns the most recent entry if multiple exist.
/// Skips entries older than 7 days so learners get content calibrated to
/// their current mastery level rather than stale cached material.
/// Rejects entries with invalid or missing HMAC signatures (cache poisoning protection).
///
/// When `current_mastery` is provided, the cache also checks that the cached
/// entry was generated for the same mastery band (low/mid/high). This ensures
/// the learner gets appropriately-leveled content after mastery changes.
///
/// When `current_model` is provided, entries generated by a different model
/// are skipped so model changes take effect immediately.
pub fn get_cached_content(
    conn: &Connection,
    concept_id: &str,
    content_type: &str,
) -> Result<Option<CachedContent>> {
    get_cached_content_personalized(conn, concept_id, content_type, None, None)
}

/// Mastery- and model-aware cache lookup.
pub fn get_cached_content_personalized(
    conn: &Connection,
    concept_id: &str,
    content_type: &str,
    current_mastery: Option<f64>,
    current_model: Option<&str>,
) -> Result<Option<CachedContent>> {
    let stale_cutoff = chrono::Utc::now()
        .checked_sub_signed(chrono::Duration::days(7))
        .map(|d| d.to_rfc3339())
        .unwrap_or_default();

    let mut stmt = conn.prepare(
        "SELECT id, concept_id, content_type, payload_json, model_version, created_at, content_hash
         FROM content_cache
         WHERE concept_id = ?1 AND content_type = ?2 AND created_at >= ?3
         ORDER BY created_at DESC
         LIMIT 1",
    )?;

    let mut rows = stmt.query(params![concept_id, content_type, stale_cutoff])?;
    match rows.next()? {
        Some(row) => {
            let entry = row_to_cached(row)?;

            // Verify HMAC integrity if a hash is present
            if let Some(ref stored_hash) = entry.content_hash {
                if let Ok(secret) = crate::cache_integrity::get_or_create_secret(conn) {
                    if !crate::cache_integrity::verify_hmac(
                        &secret,
                        &entry.concept_id,
                        &entry.content_type,
                        &entry.payload_json,
                        stored_hash,
                    ) {
                        eprintln!(
                            "Cache integrity check failed for {}:{} — discarding entry",
                            entry.concept_id, entry.content_type
                        );
                        // Delete the tampered entry
                        if let Some(id) = entry.id {
                            let _ = conn.execute(
                                "DELETE FROM content_cache WHERE id = ?1",
                                params![id],
                            );
                        }
                        return Ok(None);
                    }
                }
            }
            // Entries without a hash (pre-upgrade) are allowed but will be
            // replaced on next cache write with a signed entry.

            // If model changed, treat cached entry as stale
            if let Some(wanted_model) = current_model {
                if let Some(ref cached_model) = entry.model_version {
                    if cached_model != wanted_model {
                        eprintln!(
                            "Cache model mismatch for {}:{} (cached={}, wanted={}) — regenerating",
                            entry.concept_id, entry.content_type, cached_model, wanted_model
                        );
                        return Ok(None);
                    }
                }
            }

            // If mastery band changed, content is no longer calibrated
            if let Some(score) = current_mastery {
                let current_band = mastery_band(score);
                // Heuristic: check if the cached payload references mastery-band
                // calibration. We store the band in a comment at the end of the
                // payload on insert. If missing (pre-upgrade entry), allow it.
                let band_tag = format!("<!-- mastery_band:{} -->", current_band);
                let payload = &entry.payload_json;
                if payload.contains("<!-- mastery_band:") && !payload.contains(&band_tag) {
                    eprintln!(
                        "Cache mastery band mismatch for {}:{} (wanted={}) — regenerating",
                        entry.concept_id, entry.content_type, current_band
                    );
                    return Ok(None);
                }
            }

            Ok(Some(entry))
        }
        None => Ok(None),
    }
}

/// Invalidate cache for a concept when mastery is updated.
/// Call this after any mastery-changing event (quiz answer, project review).
pub fn invalidate_on_mastery_change(
    conn: &Connection,
    concept_id: &str,
    old_mastery: f64,
    new_mastery: f64,
) -> Result<()> {
    // Only invalidate if the mastery band actually changed
    if mastery_band(old_mastery) != mastery_band(new_mastery) {
        eprintln!(
            "Mastery band changed for {} ({} -> {}), invalidating cache",
            concept_id,
            mastery_band(old_mastery),
            mastery_band(new_mastery),
        );
        invalidate_cache(conn, concept_id, "lesson")?;
        invalidate_cache(conn, concept_id, "quiz")?;
    }
    Ok(())
}

/// Invalidate cache for all concepts when the base model setting changes.
pub fn invalidate_on_model_change(conn: &Connection) -> Result<usize> {
    let count = conn.execute("DELETE FROM content_cache", [])?;
    if count > 0 {
        eprintln!("Model change: purged {count} cache entries");
    }
    Ok(count)
}

/// Get all cache entries for a concept.
pub fn get_cache_for_concept(conn: &Connection, concept_id: &str) -> Result<Vec<CachedContent>> {
    let mut stmt = conn.prepare(
        "SELECT id, concept_id, content_type, payload_json, model_version, created_at, content_hash
         FROM content_cache
         WHERE concept_id = ?1
         ORDER BY created_at DESC",
    )?;

    let rows = stmt.query_map(params![concept_id], |row| row_to_cached(row))?;
    let mut entries = Vec::new();
    for row in rows {
        entries.push(row?);
    }
    Ok(entries)
}

/// Delete cache entries older than the given date string.
pub fn purge_cache_before(conn: &Connection, before_date: &str) -> Result<usize> {
    let count = conn.execute(
        "DELETE FROM content_cache WHERE created_at < ?1",
        params![before_date],
    )?;
    Ok(count)
}

/// Delete all cache entries for a concept and content type.
pub fn invalidate_cache(conn: &Connection, concept_id: &str, content_type: &str) -> Result<()> {
    conn.execute(
        "DELETE FROM content_cache WHERE concept_id = ?1 AND content_type = ?2",
        params![concept_id, content_type],
    )?;
    Ok(())
}

fn row_to_cached(row: &rusqlite::Row) -> Result<CachedContent> {
    Ok(CachedContent {
        id: row.get(0)?,
        concept_id: row.get(1)?,
        content_type: row.get(2)?,
        payload_json: row.get(3)?,
        model_version: row.get(4)?,
        created_at: row.get(5)?,
        content_hash: row.get(6)?,
    })
}
